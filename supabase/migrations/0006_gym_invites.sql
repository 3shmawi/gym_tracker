-- Gym accounts, part 2: invites, redeem attempts and their functions
-- (docs/decisions/gym_accounts.md §5).
--
-- The plain invite code is never stored. Only HMAC-SHA256(pepper, code) is.
-- The pepper is generated here, inside Postgres, into Supabase Vault: no
-- person, file, CI log or app ever sees it. A code is shown once, by
-- create_invite / admin_create_invites, to whoever called them.

create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------------
-- Pepper (Vault) and hashing helpers
-- ---------------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from vault.secrets where name = 'invite_pepper') then
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'invite_pepper',
      'HMAC key for invite codes and attempt IP hashes. Rotating it invalidates unused invites.'
    );
  end if;
end;
$$;

create function private.invite_pepper()
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_pepper text;
begin
  select s.decrypted_secret into v_pepper
  from vault.decrypted_secrets s
  where s.name = 'invite_pepper';
  if v_pepper is null or v_pepper = '' then
    raise exception 'invite pepper is not set' using errcode = 'XX000';
  end if;
  return v_pepper;
end;
$$;

create function private.hash_invite_code(p_code text)
returns bytea
language sql
stable
security definer
set search_path = ''
as $$
  select extensions.hmac(
    convert_to('invite:' || upper(p_code), 'utf8'),
    convert_to(private.invite_pepper(), 'utf8'),
    'sha256'
  )
$$;

create function private.hash_ip(p_ip text)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select encode(
    extensions.hmac(
      convert_to('ip:' || p_ip, 'utf8'),
      convert_to(private.invite_pepper(), 'utf8'),
      'sha256'
    ),
    'hex'
  )
$$;

-- 6 characters from 31 (no 0 O 1 I L): ~29.7 bits. Bytes >= 248 are dropped
-- so every letter is equally likely (248 = 8 * 31).
create function private.generate_invite_code()
returns text
language plpgsql
volatile
set search_path = ''
as $$
declare
  c_alphabet constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  v_code text := '';
  v_bytes bytea;
  v_byte int;
  i int;
begin
  while char_length(v_code) < 6 loop
    v_bytes := extensions.gen_random_bytes(16);
    for i in 0 .. 15 loop
      v_byte := get_byte(v_bytes, i);
      if v_byte < 248 and char_length(v_code) < 6 then
        v_code := v_code || substr(c_alphabet, (v_byte % 31) + 1, 1);
      end if;
    end loop;
  end loop;
  return v_code;
end;
$$;

revoke all on function private.invite_pepper(), private.hash_invite_code(text),
  private.hash_ip(text), private.generate_invite_code() from public, anon, authenticated;
grant execute on function private.invite_pepper(), private.hash_invite_code(text),
  private.hash_ip(text), private.generate_invite_code() to service_role;

-- ---------------------------------------------------------------------------
-- invites
-- ---------------------------------------------------------------------------
create table public.invites (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms (id) on delete cascade,
  membership_id uuid not null references public.memberships (id) on delete cascade,
  -- join: a pending member's first code. recover: new phone for a person.
  -- ('demo' arrives with the demo gym, delivery step 5.)
  kind text not null check (kind in ('join', 'recover')),
  code_hmac bytea not null unique check (octet_length(code_hmac) = 32),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  used_at timestamptz,
  -- Random id generated by the app at first launch; not a hardware id.
  bound_install_id uuid,
  revoked_at timestamptz,
  created_by uuid references public.people (id) on delete set null,
  constraint invites_expiry_window check (
    expires_at > created_at and expires_at <= created_at + interval '7 days'
  ),
  constraint invites_used_has_install check ((used_at is null) = (bound_install_id is null))
);

create index invites_membership_id_idx on public.invites (membership_id);
create index invites_gym_id_idx on public.invites (gym_id);

alter table public.invites enable row level security;
revoke all on table public.invites from anon, authenticated;
-- Managers may list invites, never the hash. No direct writes: invites are
-- made and revoked through the functions below.
grant select (id, gym_id, membership_id, kind, created_at, expires_at, used_at,
              bound_install_id, revoked_at, created_by)
  on table public.invites to authenticated;

-- May the caller manage the member behind this membership?
create function private.i_manage_membership(p_membership_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select private.i_manage_role(m.gym_id, m.role)
     from public.memberships m
     where m.id = p_membership_id),
    false
  )
$$;

revoke all on function private.i_manage_membership(uuid) from public, anon;
grant execute on function private.i_manage_membership(uuid) to authenticated, service_role;

create policy "managers read invites" on public.invites
  for select to authenticated
  using ((select private.i_manage_membership(membership_id)));

-- ---------------------------------------------------------------------------
-- invite_attempts: throttle + audit. No policies at all: only the redeem
-- function (as table owner) reads or writes it.
-- ---------------------------------------------------------------------------
create table public.invite_attempts (
  id bigint generated always as identity primary key,
  auth_user_id uuid not null,
  ip_hash text not null,
  ok boolean not null,
  at timestamptz not null default now()
);

create index invite_attempts_user_idx on public.invite_attempts (auth_user_id, at) where not ok;
create index invite_attempts_ip_idx on public.invite_attempts (ip_hash, at) where not ok;
create index invite_attempts_at_idx on public.invite_attempts (at);

alter table public.invite_attempts enable row level security;
revoke all on table public.invite_attempts from anon, authenticated;

-- Rows older than 30 days are purged. Schedule it (pg_cron, or any job that
-- calls it with the secret key); see docs/release.md.
create function public.purge_invite_attempts()
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_deleted bigint;
begin
  delete from public.invite_attempts where at < now() - interval '30 days';
  get diagnostics v_deleted = row_count;
  return v_deleted;
end;
$$;

revoke all on function public.purge_invite_attempts() from public, anon, authenticated;
grant execute on function public.purge_invite_attempts() to service_role;

-- ---------------------------------------------------------------------------
-- create_invite / revoke_invite (managers, permanent session)
-- ---------------------------------------------------------------------------
-- Returns {invite_id, code, expires_at}. The code is shown once: lost the
-- printout? Revoke and re-issue. A new invite revokes the unused older ones
-- of the same member.
create function public.create_invite(p_membership_id uuid, p_kind text default 'join')
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_m public.memberships;
  v_person uuid := private.current_person_id();
  v_code text;
  v_id uuid;
  v_expires timestamptz := now() + interval '7 days';
  v_try int := 0;
begin
  if p_kind is null or p_kind not in ('join', 'recover') then
    raise exception 'invalid_kind' using errcode = '22023';
  end if;

  select * into v_m from public.memberships where id = p_membership_id for update;
  -- Same answer for "missing" and "not yours": no probing of ids.
  if not found or not private.i_manage_role(v_m.gym_id, v_m.role) then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  if p_kind = 'join' and not (v_m.status = 'pending' and v_m.person_id is null) then
    raise exception 'invalid_membership' using errcode = '22023';
  end if;
  if p_kind = 'recover' then
    if v_m.person_id is null then
      raise exception 'invalid_membership' using errcode = '22023';
    end if;
    -- A person in another active gym cannot be moved by this gym's captain.
    if exists (
      select 1
      from public.memberships o
      join public.gyms og on og.id = o.gym_id
      where o.person_id = v_m.person_id and o.gym_id <> v_m.gym_id
        and o.status = 'active' and og.deleted_at is null
    ) then
      raise exception 'person_in_other_gym' using errcode = '22023';
    end if;
  end if;

  update public.invites
     set revoked_at = now()
   where membership_id = v_m.id and used_at is null and revoked_at is null;

  loop
    v_try := v_try + 1;
    v_code := private.generate_invite_code();
    begin
      insert into public.invites (gym_id, membership_id, kind, code_hmac, expires_at, created_by)
      values (v_m.gym_id, v_m.id, p_kind, private.hash_invite_code(v_code), v_expires, v_person)
      returning id into v_id;
      exit;
    exception when unique_violation then
      if v_try >= 5 then raise; end if;
    end;
  end loop;

  return jsonb_build_object('invite_id', v_id, 'code', v_code, 'expires_at', v_expires);
end;
$$;

create function public.revoke_invite(p_invite_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_membership uuid;
begin
  select membership_id into v_membership from public.invites where id = p_invite_id;
  if v_membership is null or not private.i_manage_membership(v_membership) then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  update public.invites
     set revoked_at = now()
   where id = p_invite_id and revoked_at is null;
end;
$$;

revoke all on function public.create_invite(uuid, text), public.revoke_invite(uuid)
  from public, anon;
grant execute on function public.create_invite(uuid, text), public.revoke_invite(uuid)
  to authenticated;

-- ---------------------------------------------------------------------------
-- admin_create_invites: run by the owner from scripts/make_invites with the
-- secret key (service_role only). N pending trainee memberships + N invites
-- in one transaction. Returns an array of
-- {membership_id, display_name, invite_id, code, expires_at}.
-- ---------------------------------------------------------------------------
create function public.admin_create_invites(
  p_gym_id uuid,
  p_count int,
  p_names text[] default null,
  p_can_edit_targets boolean default false,
  p_can_edit_plan boolean default false,
  p_can_build_own_plan boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_expires timestamptz := now() + interval '7 days';
  v_result jsonb := '[]'::jsonb;
  v_name text;
  v_member uuid;
  v_invite uuid;
  v_code text;
  i int;
begin
  if p_count is null or p_count < 1 or p_count > 200 then
    raise exception 'invalid_count' using errcode = '22023';
  end if;
  if p_names is not null and cardinality(p_names) <> p_count then
    raise exception 'invalid_names' using errcode = '22023';
  end if;
  if not exists (select 1 from public.gyms where id = p_gym_id and deleted_at is null) then
    raise exception 'gym_not_found' using errcode = '22023';
  end if;

  for i in 1 .. p_count loop
    v_name := coalesce(btrim(p_names[i]), format('Trainee %s', i));
    insert into public.memberships (
      gym_id, display_name, role, status,
      can_edit_targets, can_edit_plan, can_build_own_plan
    ) values (
      p_gym_id, v_name, 'trainee', 'pending',
      p_can_edit_targets or p_can_edit_plan, p_can_edit_plan, p_can_build_own_plan
    ) returning id into v_member;

    v_code := private.generate_invite_code();
    insert into public.invites (gym_id, membership_id, kind, code_hmac, expires_at)
    values (p_gym_id, v_member, 'join', private.hash_invite_code(v_code), v_expires)
    returning id into v_invite;

    v_result := v_result || jsonb_build_array(jsonb_build_object(
      'membership_id', v_member,
      'display_name', v_name,
      'invite_id', v_invite,
      'code', v_code,
      'expires_at', v_expires
    ));
  end loop;
  return v_result;
end;
$$;

revoke all on function public.admin_create_invites(uuid, int, text[], boolean, boolean, boolean)
  from public, anon, authenticated;
grant execute on function public.admin_create_invites(uuid, int, text[], boolean, boolean, boolean)
  to service_role;

-- ---------------------------------------------------------------------------
-- redeem_invite_core: the one transaction behind the Edge Function
-- `redeem_invite`. Only service_role may call it, because the caller's
-- identity (p_auth_user_id) and address (p_ip) are passed in, and only the
-- function (which verified the JWT) can be trusted to pass them.
--
-- It never raises for a bad code: a failure is returned as
-- {ok:false, reason} so that the attempt row survives the transaction.
-- reasons: invalid | not_found | revoked | used | expired | conflict | throttled
-- ---------------------------------------------------------------------------
create function public.redeem_invite_core(
  p_auth_user_id uuid,
  p_code text,
  p_install_id uuid,
  p_ip text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_ip_hash text;
  v_inv public.invites;
  v_m public.memberships;
  v_gym public.gyms;
  v_person uuid;
  v_target uuid;
  v_reason text;
begin
  if p_auth_user_id is null or p_code is null or p_install_id is null then
    return jsonb_build_object('ok', false, 'reason', 'invalid');
  end if;
  v_ip_hash := private.hash_ip(coalesce(nullif(left(p_ip, 64), ''), 'unknown'));

  -- One redeem at a time per auth user: the counters below stay exact.
  perform pg_advisory_xact_lock(hashtextextended(p_auth_user_id::text, 0));

  -- Throttle (not recorded: a locked-out person must not stay locked out).
  if (select count(*) from public.invite_attempts
       where auth_user_id = p_auth_user_id and not ok
         and at > now() - interval '1 hour') >= 10
     or (select count(*) from public.invite_attempts
          where ip_hash = v_ip_hash and not ok
            and at > now() - interval '1 hour') >= 30
     or (select count(*) from public.invite_attempts
          where not ok and at > now() - interval '10 minutes') > 200 then
    return jsonb_build_object('ok', false, 'reason', 'throttled');
  end if;

  if p_code !~ '^[A-HJKMNP-Z2-9]{6}$' then
    v_reason := 'not_found';
  else
    select * into v_inv
      from public.invites
     where code_hmac = private.hash_invite_code(p_code)
     for update;
    if not found then
      v_reason := 'not_found';
    end if;
  end if;

  if v_reason is null then
    select * into v_m from public.memberships where id = v_inv.membership_id for update;
    select * into v_gym from public.gyms where id = v_inv.gym_id;
    select id into v_person from public.people where auth_user_id = p_auth_user_id;

    if v_gym.id is null or v_gym.deleted_at is not null then
      v_reason := 'not_found';
    elsif v_inv.revoked_at is not null then
      v_reason := 'revoked';
    elsif v_inv.used_at is not null then
      -- The same phone retrying after a lost answer is a success, nothing else is.
      if v_inv.bound_install_id = p_install_id
         and v_person is not null and v_m.person_id = v_person and v_m.status = 'active' then
        insert into public.invite_attempts (auth_user_id, ip_hash, ok)
        values (p_auth_user_id, v_ip_hash, true);
        return private.redeem_payload(v_gym, v_m);
      end if;
      v_reason := 'used';
    elsif v_inv.expires_at <= now() then
      v_reason := 'expired';
    elsif v_inv.kind = 'join' and not (v_m.status = 'pending' and v_m.person_id is null) then
      v_reason := 'not_found';
    elsif v_inv.kind = 'recover' and v_m.person_id is null then
      v_reason := 'not_found';
    end if;
  end if;

  if v_reason is null then
    if v_inv.kind = 'join' then
      if v_person is null then
        insert into public.people (auth_user_id, display_name)
        values (p_auth_user_id, left(v_m.display_name, 40))
        returning id into v_person;
      end if;
      if exists (select 1 from public.memberships
                  where gym_id = v_m.gym_id and person_id = v_person) then
        v_reason := 'conflict';
      else
        update public.memberships
           set person_id = v_person, status = 'active', joined_at = now()
         where id = v_m.id
        returning * into v_m;
      end if;
    else
      -- recover: the person moves to this phone's auth user.
      v_target := v_m.person_id;
      if v_person is not null and v_person <> v_target then
        v_reason := 'conflict';
      elsif v_person is null and exists (
        select 1
        from public.memberships o
        join public.gyms og on og.id = o.gym_id
        where o.person_id = v_target and o.gym_id <> v_m.gym_id
          and o.status = 'active' and og.deleted_at is null
      ) then
        v_reason := 'conflict';
      else
        if v_person is null then
          -- RLS keys on people.auth_user_id: the old session is cut off here.
          update public.people set auth_user_id = p_auth_user_id where id = v_target;
        end if;
        if v_m.status <> 'active' then
          update public.memberships
             set status = 'active', joined_at = now(), ended_at = null, ended_by = null
           where id = v_m.id
          returning * into v_m;
        end if;
      end if;
    end if;
  end if;

  if v_reason is not null then
    insert into public.invite_attempts (auth_user_id, ip_hash, ok)
    values (p_auth_user_id, v_ip_hash, false);
    return jsonb_build_object('ok', false, 'reason', v_reason);
  end if;

  update public.invites
     set used_at = now(), bound_install_id = p_install_id
   where id = v_inv.id;
  insert into public.invite_attempts (auth_user_id, ip_hash, ok)
  values (p_auth_user_id, v_ip_hash, true);
  return private.redeem_payload(v_gym, v_m);
end;
$$;

create function private.redeem_payload(p_gym public.gyms, p_m public.memberships)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select jsonb_build_object(
    'ok', true,
    'gym', jsonb_build_object(
      'id', p_gym.id,
      'name', p_gym.name,
      'logo_path', p_gym.logo_path,
      'history_after_end', p_gym.history_after_end
    ),
    'membership_id', p_m.id,
    'role', p_m.role,
    'permissions', jsonb_build_object(
      'edit_targets', p_m.can_edit_targets,
      'edit_plan', p_m.can_edit_plan,
      'build_own_plan', p_m.can_build_own_plan
    )
  )
$$;

revoke all on function private.redeem_payload(public.gyms, public.memberships)
  from public, anon, authenticated;
grant execute on function private.redeem_payload(public.gyms, public.memberships) to service_role;

revoke all on function public.redeem_invite_core(uuid, text, uuid, text)
  from public, anon, authenticated;
grant execute on function public.redeem_invite_core(uuid, text, uuid, text) to service_role;
