-- Trial: every new user (anonymous sign-in included) gets the default plan
-- through ensure_trial_plan(). The coach's 5-day split is the default.
-- Sets/reps default to 3 x 12 (abs 3 x 15) until the coach confirms them.

alter table public.plans add column if not exists is_default boolean not null default false;

create unique index if not exists plans_one_default
  on public.plans (is_default) where is_default;

-- Assigns the default plan to the caller if they have no active plan.
-- Returns the caller's active plan id (null when there is no default plan).
create or replace function public.ensure_trial_plan()
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_plan uuid;
begin
  if v_uid is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;

  -- Profiles are created by the sign-up trigger; this covers users that
  -- existed before it.
  insert into public.profiles (id) values (v_uid) on conflict (id) do nothing;

  select plan_id into v_plan from public.plan_assignments
  where member_id = v_uid and active;
  if found then
    return v_plan;
  end if;

  select id into v_plan from public.plans where is_default;
  if v_plan is null then
    return null;
  end if;

  insert into public.plan_assignments (plan_id, member_id)
  values (v_plan, v_uid)
  on conflict do nothing;
  return v_plan;
end;
$$;

revoke execute on function public.ensure_trial_plan() from public, anon;
grant execute on function public.ensure_trial_plan() to authenticated;

