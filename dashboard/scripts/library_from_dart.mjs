// The dashboard's copy of the app's exercise library (ids, both names, muscle,
// whether the library has a how-to video). The app's Dart files are the
// source of truth; test/library.test.ts fails when this copy drifts.
//
//   node scripts/library_from_dart.mjs > src/exercises/library.ts
//
// docs/features/dashboard.md → "D2 Exercise media".
import { readFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
export const CATALOG = new URL('lib/features/library/data/exercise_catalog.dart', root);
export const VIDEOS = new URL('lib/features/library/data/exercise_videos.dart', root);

const str = "'((?:[^'\\\\]|\\\\.)*)'";
const ENTRY = new RegExp(
  `id: '([a-z][a-z0-9_]*)',\\s*name: LocalizedName\\(\\s*ar: ${str},\\s*en: ${str},?\\s*\\),((?:\\s*[a-zA-Z]+: [^,\\n]+,)*)\\s*\\),\\s*muscle: MuscleGroup\\.([a-z]+)`,
  'g',
);
const VIDEO = /'([a-z][a-z0-9_]*)':\s*YouTubeVideoRef\(\s*'([A-Za-z0-9_-]{11})'/g;
const unescape = (s) => s.replace(/\\(.)/g, '$1');

// The app's Exercise defaults (workout_plan.dart), overridden per entry.
const DEFAULTS = { sets: 3, reps: 12, rest: 90, step: 2.5 };
const FIELDS = { targetSets: 'sets', targetReps: 'reps', restSeconds: 'rest', weightStep: 'step' };
function targets(text) {
  const out = { ...DEFAULTS };
  for (const m of text.matchAll(/([a-zA-Z]+): ([0-9.]+),/g)) {
    const key = FIELDS[m[1]];
    if (key) out[key] = Number(m[2]);
  }
  return out;
}

/** Parses the two Dart files' text into the library entries, in the app's order. */
export function parseLibrary(catalogText, videosText) {
  const videos = new Set([...videosText.matchAll(VIDEO)].map((m) => m[1]));
  return [...catalogText.matchAll(ENTRY)].map((m) => ({
    id: m[1],
    ar: unescape(m[2]),
    en: unescape(m[3]),
    muscle: m[5],
    libraryVideo: videos.has(m[1]),
    ...targets(m[4] ?? ''),
  }));
}

export function readLibrary() {
  return parseLibrary(readFileSync(CATALOG, 'utf8'), readFileSync(VIDEOS, 'utf8'));
}

/** The TypeScript file, as written to src/exercises/library.ts. */
export function libraryModule(entries) {
  const lines = entries.map((e) => `  ${JSON.stringify(e)},`);
  return [
    '// Generated by scripts/library_from_dart.mjs from the app\'s',
    '// lib/features/library/data/exercise_catalog.dart and exercise_videos.dart.',
    '// Do not edit by hand: run `node scripts/library_from_dart.mjs > src/exercises/library.ts`.',
    "import type { LibraryExercise } from './types';",
    '',
    'export const LIBRARY: readonly LibraryExercise[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.stdout.write(libraryModule(readLibrary()));
}
